package com.xiangqi.v2.config

/**
 * 深度默认值 12 → 18 → 22，以及**已有安装怎么跟上**。
 *
 * 只改常量是不够的：`prefs.getInt(KEY_DEPTH, DEFAULT_DEPTH)` 在用户动过一次滑块之后
 * 就再也读不到默认值了 —— 那批机器会一直停在旧值，改了等于没改。但反过来无差别覆盖
 * 又会把「用户主动调到 8 图快」的人按回去，那是不该替他做的决定。
 *
 * 所以判据只有一条：**存着的值正好等于某个历史默认值**，才认为它只是"没调过"。
 * 调过 8 / 10 / 16 的一律不动。迁移只做一次（用 [FLAG] 记住），之后用户再手动调回去
 * 就是他自己的选择，不会被下次启动改回来。
 *
 * ## 为什么一路往上抬是安全的
 *
 * 引擎收到的是 `go depth N movetime M`，**先到者生效**。深度只是上限，真正的兜底是
 * 思考时间（默认 2500ms）—— 所以调高深度不会让复杂局面卡更久，它只会让原本
 * 提前触顶的简单局面把时间用满。
 *
 * ## 为什么是 22 而不是 18
 *
 * 实测（皮卡鱼 2026-09-06，单线程，单位秒）：
 *
 * | 局面 | d18 | d20 | d22 | d24 |
 * |---|---|---|---|
 * | 中炮对屏风马 | 0.68 | 1.75 | 2.51 | 4.07 |
 * | 过宫炮 | 0.17 | 0.47 | 0.70 | 0.90 |
 * | 中局复杂 | 0.39 | 0.77 | 0.94 | 1.61 |
 *
 * 桌面单线程约 90 万 nps，手机大核通常只有它的三分之一上下。也就是说 18 层在手机上
 * 大致 0.5~2 秒就到顶了：**2500ms 的预算里有一多半根本没花出去**。而 `movetime`
 * 是硬上限，把 18 抬到 22 不会让任何局面变慢，只把原本空转的那段算力用起来。
 *
 * 为什么不干脆不设上限：22 层已经比"2500ms 内能算到的深度"高一档（复杂局面到不了），
 * 等于既吃满了时间预算，又保留了"简单局面提前返回"这个省电、跟手的性质。
 */
object DepthDefault {

    /** 最早的历史默认值。 */
    const val LEGACY = 12

    /** 上一版默认值。已经升级过一次的安装存的是这个数。 */
    const val PREVIOUS = 18

    /** 当前默认深度。 */
    const val CURRENT = 22

    /** 迁移标志键。存下之后不再迁移，用户后续的选择才算数。 */
    const val FLAG = "depth_migrated_22"

    /**
     * 该把存着的深度改成多少；返回 null 表示不动。
     *
     * 两个历史默认值都认：跳版本升级的机器可能还停在 12，正常升级的在 18。
     * 只认一个会让前者永远停在最早那个值。
     *
     * @param stored 已存的深度；null 表示从来没存过（新默认值自然生效，不必写）
     * @param migrated 是否已经迁移过
     */
    fun migrate(stored: Int?, migrated: Boolean): Int? = when {
        migrated -> null
        stored == null -> null
        stored == LEGACY || stored == PREVIOUS -> CURRENT
        else -> null
    }
}
